def test_three_agent_workflow_uses_mocked_local_services(monkeypatch, tmp_path):
    import agents.knowledge_agent as knowledge_agent
    import agents.patient_agent as patient_agent
    import agents.response_agent as response_agent
    import database.db as db

    database = tmp_path / "workflow.sqlite3"
    db.init_db(database)
    patient = db.create_patient("Casey", 20, allergies="Pollen", db_path=database)
    monkeypatch.setattr(patient_agent, "get_patient", lambda patient_id: db.get_patient(patient_id, database))
    monkeypatch.setattr(
        patient_agent,
        "get_patient_consultations",
        lambda patient_id, limit=20: db.get_patient_consultations(patient_id, limit, database),
    )
    monkeypatch.setattr(
        knowledge_agent,
        "retrieve",
        lambda question, top_k=3: [
            {
                "text": "Pollen can trigger seasonal allergy symptoms.",
                "title": "Seasonal allergic rhinitis",
                "category": "Allergies",
                "source_name": "MedlinePlus",
                "source_url": "https://medlineplus.gov/",
                "distance": 0.1,
            }
        ],
    )
    monkeypatch.setattr(response_agent, "generate_response", lambda prompt, model: "A cautious local test response.")

    result = run_assistant("Could pollen be related?", patient_id=patient.id)
    assert result["answer"] == "A cautious local test response."
    assert [item["agent"] for item in result["agent_status"]] == [
        "Patient Context Agent",
        "Medical Knowledge Agent",
        "Medical Response Agent",
    ]
    assert result["patient_context"]["allergies"] == "Pollen"
    assert result["retrieved_documents"][0]["source_name"] == "MedlinePlus"