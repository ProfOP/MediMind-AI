from rag.ingest import chunk_text, ingest_knowledge_base, load_documents
from database.db import (
    create_patient,
    get_patient,
    get_patient_consultations,
    init_db,
    save_consultation,
)
from graph.workflow import is_emergency, run_assistant


def test_patient_and_consultation_persist_in_sqlite(tmp_path):
    database = tmp_path / "patients.sqlite3"
    init_db(database)
    patient = create_patient("Jordan", 21, allergies="Pollen", db_path=database)
    save_consultation(patient.id, "What is a seasonal allergy?", "General information only.", database)

    loaded = get_patient(patient.id, database)
    history = get_patient_consultations(patient.id, db_path=database)
    assert loaded is not None
    assert loaded.allergies == "Pollen"
    assert len(history) == 1
    assert history[0].user_query == "What is a seasonal allergy?"


def test_invalid_patient_age_is_rejected():
    try:
        create_patient("Jordan", 150)
    except ValueError as exc:
        assert "between 0 and 125" in str(exc)
    else:
        raise AssertionError("Expected invalid age to be rejected")


def test_local_knowledge_files_and_chunking():
    documents = load_documents()
    assert documents
    assert all(item["source"].get("url") for item in documents)
    chunks = chunk_text("one two three four five", chunk_words=3, overlap_words=1)
    assert chunks == ["one two three", "three four five"]


def test_chroma_ingestion_and_retrieval_with_local_embedding_stub(tmp_path, monkeypatch):
    import rag.ingest as ingest
    import rag.retriever as retriever

    monkeypatch.setattr(ingest, "embed_texts", lambda texts: [[1.0, 0.0] for _ in texts])
    monkeypatch.setattr(retriever, "embed_texts", lambda texts: [[1.0, 0.0] for _ in texts])
    persist = tmp_path / "chroma"
    count = ingest_knowledge_base(persist_directory=persist)
    matches = retriever.retrieve("allergy pollen", top_k=3, persist_directory=str(persist))

    assert count >= len(load_documents())
    assert 1 <= len(matches) <= 3
    assert all(item["source_url"].startswith("https://") for item in matches)


